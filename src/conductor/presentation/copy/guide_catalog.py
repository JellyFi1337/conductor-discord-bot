def _cmd(
    section: str,
    path: str,
    key: str | None = None,
    *,
    who: str | None = None,
    summary: str,
    details: tuple[str, ...],
    params: tuple[tuple[str, str], ...] = (),
) -> GuideCommand:
    return GuideCommand(
        path=path,
        key=key,
        who=who,
        summary=summary,
        details=details,
        params=params,
        kind=KIND_COMMAND,
        section=section,
    )


def _btn(
    section: str,
    path: str,
    key: str | None = None,
    *,
    who: str | None = None,
    summary: str,
    details: tuple[str, ...],
    params: tuple[tuple[str, str], ...] = (),
) -> GuideCommand:
    return GuideCommand(
        path=path,
        key=key,
        who=who,
        summary=summary,
        details=details,
        params=params,
        kind=KIND_BUTTON,
        section=section,
    )


