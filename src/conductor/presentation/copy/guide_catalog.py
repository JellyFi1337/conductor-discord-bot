def section_commands(section: str) -> tuple[GuideCommand, ...]:
    return CATALOG.get(section, ())


def catalog_entries() -> tuple[GuideCommand, ...]:
    items: list[GuideCommand] = []
    for rows in CATALOG.values():
        items.extend(rows)
    return tuple(items)


def catalog_paths() -> tuple[str, ...]:
    seen: list[str] = []
    for item in catalog_entries():
        if item.kind != KIND_COMMAND:
            continue
        if item.path not in seen:
            seen.append(item.path)
    return tuple(seen)


def catalog_command_paths() -> tuple[str, ...]:
    return catalog_paths()

